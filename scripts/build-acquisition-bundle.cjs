/* Deterministic browser/offline bundle; run after changing a source module. */
'use strict';
const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const { validateDataset } = require('../acquisition-metadata.js');
const root = join(__dirname, '..');
const assetPath = join(root, 'assets', 'acquisition-pilot.js');

function readModule(filename) {
  const source = readFileSync(join(root, filename), 'utf8');
  if (/<\/script/i.test(source)) throw new Error(`${filename} contains an unsafe inline script terminator.`);
  return source.trimEnd();
}
function generateBundle() {
  const metadataSource = readModule('acquisition-metadata.js');
  const uiSource = readModule('acquisition-ui.js');
  const parsedDataset = JSON.parse(readFileSync(join(root, 'data', 'acquisition.v1.json'), 'utf8'));
  const checked = validateDataset(parsedDataset);
  if (!checked.ok) {
    const diagnostics = checked.issues.map(issue => `${issue.path} [${issue.code}]: ${issue.message}`).join('\n');
    throw new Error(`data/acquisition.v1.json failed canonical validation:\n${diagnostics}`);
  }
  const dataset = JSON.stringify(checked.dataset).replace(/</g, '\\u003c');
  // Each module gets an isolated CommonJS context; the runtime needs no loader.
  // The named initializer encloses every dependency needed by offlineSource().
  const initializer = `function initializeAcquisition(root) {
  'use strict';
  const metadataModule = { exports: {} };
  (function (module, exports) {
${metadataSource}
  })(metadataModule, metadataModule.exports);
  const uiModule = { exports: {} };
  (function (module, exports) {
${uiSource}
  })(uiModule, uiModule.exports);
  const dataset = ${dataset};
  const ui = uiModule.exports.createAcquisitionUI(metadataModule.exports, dataset);
  root.BG3AcquisitionUI = Object.freeze({
    render: ui.render,
    renderableReviewedRoutesFor: ui.renderableReviewedRoutesFor,
    offlineSource() { return '(' + initializeAcquisition.toString() + ')(globalThis);'; }
  });
}`;
  return '/* Generated by scripts/build-acquisition-bundle.cjs. Do not edit. */\n(' + initializer + ')(globalThis);\n';
}

module.exports = Object.freeze({ generateBundle });
if (require.main === module) writeFileSync(assetPath, generateBundle(), 'utf8');
